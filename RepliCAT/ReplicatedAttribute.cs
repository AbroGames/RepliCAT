namespace RepliCAT;

/// <summary>
/// Помечает поле или свойство как реплицируемое. Член попадает в дельту, когда его значение
/// отличается от последнего отправленного (базовой копии, baseline).<br/>
/// Для автосвойства атрибут можно повесить как на само свойство, так и на его поле
/// (<c>[field: Replicated]</c>). Если при применении данных на клиенте нужны побочные эффекты сеттера,
/// атрибут следует вешать на свойство.
/// </summary>
[AttributeUsage(AttributeTargets.Field | AttributeTargets.Property)]
public sealed class ReplicatedAttribute : Attribute
{
    /// <summary>
    /// Manual-член: не сравнивается с базовой копией автоматически. Отправляется только при полной
    /// синхронизации (первая дельта, новый вложенный объект или элемент коллекции, снимок) и после
    /// <see cref="ManualReplication.MarkDirty"/> для владельца и имени члена, причем всегда целиком.<br/>
    /// Снимок пишет manual-члены из <b>живого</b> объекта, поэтому новый клиент получает текущее значение,
    /// даже если член не был помечен.<br/>
    /// Manual-объект или manual-коллекция делают manual все свое поддерево: изменения внутри него
    /// (в том числе <see cref="ManualReplication.MarkDirty"/> для вложенных объектов) не отправляются,
    /// пока не помечен сам член. <see cref="Tolerance"/> на manual-член не влияет.
    /// </summary>
    public bool Manual { get; set; }

    /// <summary>
    /// Допуск сравнения. Значение считается измененным, если максимальная по компонентам разница
    /// с последним отправленным значением больше допуска. 0 — точное сравнение.<br/>
    /// Поддерживается для тех же типов, что и <see cref="QuantizeAttribute"/>; может сочетаться с ним
    /// (тогда должны выполняться оба условия). Должен быть конечным неотрицательным числом.
    /// </summary>
    public double Tolerance { get; set; }
}
